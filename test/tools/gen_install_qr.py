"""gen_install_qr.py -- writes install_qr_fixture.json: reference QR matrices for test/tools/install_vectors.js, made by
the `qrcode` Python package (a dev-machine reference; nothing at run time needs it). For each text and each of the eight
masks: byte mode, error correction M, the smallest version that fits, no border, rows as "0"/"1" strings. The installer's
own encoder (site/install/install.js qrEncode) must give the same modules for every mask.

Usage (once, when the texts change): python test/tools/gen_install_qr.py
"""
import json
import os

import qrcode
from qrcode.util import MODE_8BIT_BYTE, QRData

HERE = os.path.dirname(os.path.abspath(__file__))
TEXTS = [
    "WIFI:T:WPA;S:fauxcloud-setup-3F0A;P:fauxcloud;;",   # the installer's payload: version 4
    "WIFI:T:WPA;S:fauxcloud-setup-00FF;P:fauxcloud;;",
    "fauxcloud",                                         # version 1
    "x" * 110,                                           # version 7: the version-information blocks
    "z" * 140,                                           # version 8: two block groups
    "y" * 170,                                           # version 9
    "w" * 200,                                           # version 10: the 16-bit character count
]


def matrix(text, mask):
    q = qrcode.QRCode(version=None, error_correction=qrcode.constants.ERROR_CORRECT_M, border=0, mask_pattern=mask)
    q.add_data(QRData(text.encode("utf-8"), mode=MODE_8BIT_BYTE))
    q.make(fit=True)
    return q.version, ["".join("1" if c else "0" for c in row) for row in q.get_matrix()]


def main():
    out = []
    for t in TEXTS:
        masks = []
        for k in range(8):
            v, rows = matrix(t, k)
            masks.append(rows)
        out.append({"text": t, "version": v, "masks": masks})
    path = os.path.join(HERE, "install_qr_fixture.json")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump({"_note": "GENERATED by test/tools/gen_install_qr.py (the qrcode package): do not edit", "codes": out}, f,
                  indent=1)
        f.write("\n")
    print("wrote %s (%d texts x 8 masks)" % (path, len(out)))


if __name__ == "__main__":
    main()
