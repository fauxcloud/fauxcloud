#!/usr/bin/env python3
"""site_versions.py -- site/firmware/versions.json, the list the browser installer at /install/ reads, from the boards
of site/boards.json and the published releases. Stdlib only.

Input: the GitHub Releases API output (`gh api repos/<org>/<repo>/releases`, a JSON list). Drafts are skipped, and so
is a release without the board's factory zip or whose tag is not "v" + a semantic version. Versions are newest first
(by publication date), at most --keep of them; a pre-release is listed and marked. Each version carries the zip's url,
its size, its SHA-256 (the asset's `digest` from the API, else the release's SHA256SUMS asset) and the publication
date; the SHA-256 is looked up only for the versions kept.

--mirror DIR copies every listed zip into DIR/<version>/ (checked against its SHA-256) and lists it at the same-origin
path --mirror-url + <version>/<name>, so the installer never needs a cross-origin download (the site workflow runs it
with DIR outside the tree and copies DIR into the built site after its leak gate; a DIR of site/firmware/ is
gitignored and tools/build_site.py copies it into the build, for a local look). Without
--mirror the url is the release asset's own download address, which works only if that host allows a cross-origin
fetch (site/README.md, "The installer's firmware files").

With no release at all the list holds one row "from the first release" with url null, as the committed placeholder.

Usage
  gh api "repos/fauxcloud/fauxcloud/releases?per_page=30" > releases.json
  python -I tools/site_versions.py --releases releases.json [--boards site/boards.json] [--out site/firmware/versions.json]
      [--mirror site/firmware] [--mirror-url /firmware/] [--keep 5]
"""
import argparse
import hashlib
import json
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION_RX = re.compile(r"^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?$")
SHA_RX = re.compile(r"^[0-9a-f]{64}$")
PLACEHOLDER = {"version": "from the first release", "url": None, "sha256": None, "size": None, "date": None,
               "prerelease": False}
NOTE = ("GENERATED by tools/site_versions.py from site/boards.json and the published releases; the installer at "
        "/install/ reads this file. Do not edit by hand.")
BOARD_KEYS = ("label", "chip", "flash_size", "photo", "photo_size")


class Fail(Exception):
    pass


def fetch(url):
    """The bytes at `url` (the release asset downloads: HTTPS, redirects followed)."""
    req = urllib.request.Request(url, headers={"User-Agent": "fauxcloud-site-build", "Accept": "application/octet-stream"})
    with urllib.request.urlopen(req, timeout=60) as r:  # noqa: S310 -- the URLs come from the GitHub API output
        return r.read()


def check_boards(boards):
    b = boards.get("boards")
    if not isinstance(b, dict) or not b:
        raise Fail("boards.json: no boards")
    for bid, e in b.items():
        if not re.match(r"^[a-z0-9-]+$", bid):
            raise Fail("boards.json: board id %r: lower-case letters, digits and dashes only" % bid)
        for k in BOARD_KEYS + ("asset",):
            if k not in e:
                raise Fail("boards.json: %s has no %s" % (bid, k))
        if "{version}" not in e["asset"] or not e["asset"].endswith(".zip"):
            raise Fail("boards.json: %s asset must be a zip name with {version}" % bid)
    return b


def sums_of(text):
    """SHA256SUMS text -> {name: sha256}."""
    out = {}
    for line in text.splitlines():
        m = re.match(r"^([0-9a-f]{64})\s+\*?(\S+)$", line.strip())
        if m:
            out[m.group(2)] = m.group(1)
    return out


def asset_sha(release, asset, get):
    """The asset's SHA-256: the API's digest ("sha256:<hex>"), else its line in the release's SHA256SUMS."""
    d = asset.get("digest") or ""
    if d.startswith("sha256:") and SHA_RX.match(d[7:]):
        return d[7:]
    sums = next((a for a in release.get("assets", []) if a.get("name") == "SHA256SUMS"), None)
    if sums:
        sha = sums_of(get(sums["browser_download_url"]).decode("utf-8", "replace")).get(asset["name"])
        if sha:
            return sha
    raise Fail("%s: no SHA-256 for %s (no digest, no SHA256SUMS line)" % (release.get("tag_name"), asset["name"]))


def semver_key(v):
    """A sort key: MAJOR.MINOR.PATCH as numbers, a release above its pre-releases, pre-release fields by semver rules."""
    m = VERSION_RX.match(v)
    pre = (m.group(4) or "")[1:]
    fields = tuple((0, int(f), "") if f.isdigit() else (1, 0, f) for f in pre.split(".")) if pre else ()
    return (int(m.group(1)), int(m.group(2)), int(m.group(3)), 0 if pre else 1, fields)


def versions(releases, board, get, keep):
    """[(version row, asset name)] of one board, newest first (publication date, then the version), at most `keep`;
    the SHA-256 is looked up only for the rows kept."""
    rows = []
    for rel in releases:
        if rel.get("draft"):
            continue
        tag = rel.get("tag_name") or ""
        ver = tag[1:] if tag.startswith("v") else ""
        if not VERSION_RX.match(ver):
            continue
        name = board["asset"].replace("{version}", ver)
        asset = next((a for a in rel.get("assets", []) if a.get("name") == name), None)
        if not asset:
            continue
        date = (rel.get("published_at") or rel.get("created_at") or "")[:10] or None
        size = asset.get("size")
        if not isinstance(size, int) or size <= 0:
            raise Fail("%s: %s has no size in the API output" % (tag, name))
        rows.append((rel, asset, {"version": ver, "url": asset["browser_download_url"], "sha256": None, "size": size,
                                  "date": date, "prerelease": bool(rel.get("prerelease"))}, name))
    rows.sort(key=lambda r: (r[2]["date"] or "", semver_key(r[2]["version"])), reverse=True)
    out = []
    for rel, asset, row, name in rows[:keep]:
        row["sha256"] = asset_sha(rel, asset, get)
        out.append((row, name))
    return out


def build(boards, releases, get=fetch, mirror=None, mirror_url="/firmware/", keep=5):
    """The versions.json document. With `mirror`, each zip is downloaded into mirror/<version>/ and listed there."""
    out = {"_note": NOTE, "boards": {}}
    for bid, b in check_boards(boards).items():
        rows = []
        for row, name in versions(releases, b, get, keep):
            if mirror is not None:
                data = get(row["url"])
                if len(data) != row["size"] or hashlib.sha256(data).hexdigest() != row["sha256"]:
                    raise Fail("%s: the downloaded %s does not match its SHA-256" % (row["version"], name))
                folder = os.path.join(mirror, row["version"])
                os.makedirs(folder, exist_ok=True)
                with open(os.path.join(folder, name), "wb") as f:
                    f.write(data)
                row["url"] = "%s%s/%s" % (mirror_url, row["version"], name)
            rows.append(row)
        out["boards"][bid] = dict({k: b[k] for k in BOARD_KEYS}, versions=rows or [dict(PLACEHOLDER)])
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(prog="site_versions.py", description="Write site/firmware/versions.json from the releases.")
    ap.add_argument("--releases", required=True, help="the GitHub Releases API output (a JSON list)")
    ap.add_argument("--boards", default=os.path.join(ROOT, "site", "boards.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "site", "firmware", "versions.json"))
    ap.add_argument("--mirror", metavar="DIR", help="copy the zips into DIR/<version>/ and list them at --mirror-url")
    ap.add_argument("--mirror-url", default="/firmware/")
    ap.add_argument("--keep", type=int, default=5, help="versions per board, newest first (default 5)")
    a = ap.parse_args(argv)
    try:
        with open(a.boards, encoding="utf-8") as f:
            boards = json.load(f)
        with open(a.releases, encoding="utf-8") as f:
            releases = json.load(f)
        if not isinstance(releases, list):
            raise Fail("--releases: expected the API's JSON list of releases")
        doc = build(boards, releases, mirror=a.mirror, mirror_url=a.mirror_url, keep=a.keep)
    except (Fail, OSError, ValueError) as e:
        print("site_versions: %s" % e, file=sys.stderr)
        return 1
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(doc, indent=2) + "\n")
    for bid, b in doc["boards"].items():
        print("site_versions: %s: %s" % (bid, ", ".join(v["version"] for v in b["versions"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
